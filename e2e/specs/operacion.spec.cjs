const {test,expect}=require('@playwright/test');
test('Login → mesa → pedido → producto → persistencia → cancelación con stock reintegrado',async({page,request})=>{
 expect(process.env.E2E_DATABASE).toMatch(/^dj_v1_e2e_[a-f0-9]{32}$/);
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/login');
 await page.getByPlaceholder('correo@dondejuanca.com').fill('e2e-admin@example.invalid');
 await page.getByPlaceholder('Ingresa tu contraseña').fill(process.env.E2E_PASSWORD);
 await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
 await expect(page).toHaveURL(/dashboard/);
 await page.getByLabel('Buscar en DondeJuanca').fill('mesas');
 await page.getByLabel('Buscar en DondeJuanca').press('Enter');
 await expect(page).toHaveURL(/operacion\/mesas/);
 await page.getByRole('button',{name:'Nuevo pedido',exact:true}).click();
 await page.getByRole('combobox',{name:'Mesa',exact:true}).selectOption('e2e-mesa');
 await page.getByLabel('Buscar cliente',{exact:true}).fill('E2E Cliente');
 await page.getByRole('button',{name:'Seleccionar a E2E Cliente',exact:true}).click();
 await page.getByRole('combobox',{name:'Responsable del pedido',exact:true}).selectOption('e2e-admin');
 await page.getByRole('button',{name:'Crear pedido',exact:true}).click();
 await expect(page).toHaveURL(/operacion\/pedidos\?pedido=/);
 const pedido=new URL(page.url()).searchParams.get('pedido');expect(pedido).toBeTruthy();
 await page.getByRole('combobox',{name:'Producto',exact:true}).selectOption('e2e-product');
 await page.getByLabel('Cantidad',{exact:true}).fill('2');
 await page.getByRole('button',{name:'Agregar producto',exact:true}).click();
 await expect(page.getByRole('status').filter({hasText:'Producto agregado'})).toBeVisible();
 await expect(page.getByText(/\$\s*2\.844,44/).first()).toBeVisible();
 const login=await request.post(process.env.E2E_API_URL+'/usuarios/login',{data:{correo:'e2e-admin@example.invalid',contrasena:process.env.E2E_PASSWORD}});expect(login.status()).toBe(200);
 const token=(await login.json()).token,headers={Authorization:'Bearer '+token};
 const products=await request.get(process.env.E2E_API_URL+'/productos',{headers});expect((await products.json()).datos.find(p=>p.id==='e2e-product').cantidad_disponible).toBe(48);
 await page.reload();
 await expect(page.getByRole('button',{name:'Cancelar producto',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Cancelar producto',exact:true}).click();
 await page.getByRole('button',{name:'Confirmar cancelación',exact:true}).click();
 await expect(page.getByRole('status').filter({hasText:'Producto cancelado'})).toBeVisible();
 const after=await request.get(process.env.E2E_API_URL+'/productos',{headers});expect((await after.json()).datos.find(p=>p.id==='e2e-product').cantidad_disponible).toBe(50);
 const detail=await request.get(process.env.E2E_API_URL+'/pedidos/'+pedido,{headers});expect((await detail.json()).datos.items[0].estado).toBe('cancelado');
 expect(errors).toEqual([]);
});
